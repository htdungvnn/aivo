/**
 * Generates the D1 migration SQL for the Better Auth tables.
 *
 * Run with: `pnpm --filter api db:schema`
 *
 * The DDL is compiled by Better Auth itself, driven by the same `authConfig`
 * the Worker runs, so the migration can never drift from what the library
 * actually expects. Regenerate this file whenever the auth configuration
 * changes.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { getMigrations } from "better-auth/db/migration";

import { authConfig } from "../src/auth/config.ts";
import { createEmptyD1Stub } from "./d1-stub.ts";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, "../migrations/0001_auth.sql");

const database = createEmptyD1Stub();
const plan = await getMigrations({ ...authConfig, database: database as never });

if (plan.toBeAdded.length > 0) {
  console.warn(
    "Existing tables need extra columns; add them to the migration manually:",
    plan.toBeAdded.map((table) => table.table).join(", "),
  );
}

const ddl = await plan.compileMigrations();

const header = [
  "-- Generated by `pnpm --filter api db:schema`.",
  "-- Do not edit by hand: regenerate instead.",
  "",
].join("\n");

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${header}\n${ddl}\n`, "utf8");

console.log(`Wrote ${outFile}`);
